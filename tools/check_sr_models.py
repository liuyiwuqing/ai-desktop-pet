#!/usr/bin/env python3
"""验证 ESP-SR 固定模型包并生成运行时完整性校验常量。"""
import argparse
import csv
import hashlib
from pathlib import Path
import struct

MODELS = {'wn9_xiaoaitongxue', 'vadnet1_medium'}
LIMIT = 960 * 1024


def check(data, partition_table):
    rows = list(csv.reader(line for line in partition_table.read_text().splitlines()
                           if line.strip() and not line.lstrip().startswith('#')))
    partitions = [row for row in rows if row[0].strip() == 'model']
    if (len(partitions) != 1 or len(partitions[0]) < 5 or
            [item.strip() for item in partitions[0][1:3]] != ['data', 'spiffs'] or
            int(partitions[0][3].strip(), 0) != 0xE20000 or
            int(partitions[0][4].strip(), 0) != 0x100000):
        raise ValueError('expected the fixed 1 MiB model partition at 0xE20000')
    if not 4 < len(data) <= LIMIT:
        raise ValueError('model image must be nonempty and <= 960 KiB')
    count, = struct.unpack_from('<I', data)
    if count != 2:
        raise ValueError('expected exactly WakeNet9 xiaoaitongxue and VADNet1 medium')
    cursor, models, ranges = 4, set(), []

    def name(raw):
        if b'\0' not in raw or not raw.split(b'\0', 1)[0]:
            raise ValueError('model/file name must be nonempty and NUL terminated')
        return raw.split(b'\0', 1)[0].decode('ascii')

    for _ in range(count):
        model, files = struct.unpack_from('<32sI', data, cursor)
        cursor += 36
        model = name(model)
        if model in models or not 1 <= files <= 8:
            raise ValueError('duplicate model or unsupported file count')
        models.add(model)
        names = set()
        for _ in range(files):
            raw, start, size = struct.unpack_from('<32sII', data, cursor)
            cursor += 40
            filename = name(raw)
            if filename in names or size == 0 or start > len(data) or size > len(data) - start:
                raise ValueError('invalid model file range/name')
            names.add(filename)
            ranges.append((start, start + size))
    if models != MODELS:
        raise ValueError(f'unsupported model selection: {sorted(models)}')
    end = cursor
    for start, stop in sorted(ranges):
        if start != end:
            raise ValueError('model payload is overlapping or has a gap')
        end = stop
    if end != len(data):
        raise ValueError('model payload is truncated or has trailing bytes')
    return hashlib.sha256(data).digest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--image', required=True, type=Path)
    parser.add_argument('--partition-table', required=True, type=Path)
    parser.add_argument('--header', required=True, type=Path)
    args = parser.parse_args()
    try:
        data = args.image.read_bytes()
        digest = check(data, args.partition_table)
    except (OSError, ValueError, struct.error) as error:
        parser.exit(1, f'ESP-SR package rejected: {error}\n')
    source = ('/* Generated by tools/check_sr_models.py. */\n#pragma once\n'
              f'#define PET_SR_MODEL_IMAGE_BYTES {len(data)}u\n'
              'static const unsigned char pet_sr_model_sha256[32] = {\n    ' +
              ', '.join(f'0x{byte:02x}' for byte in digest) + '\n};\n')
    args.header.parent.mkdir(parents=True, exist_ok=True)
    if not args.header.exists() or args.header.read_text() != source:
        args.header.write_text(source)
    print(f'ESP-SR model image: {len(data)} B / {LIMIT} B; SHA256 {digest.hex()}')


if __name__ == '__main__':
    main()
