#!/usr/bin/env python3
"""Generate C and TypeScript contracts from config/schemas (JSON Schema subset).

The schemas are the single source of truth for device configuration. This tool
only depends on the Python standard library and intentionally rejects schema
keywords it does not understand, so an unsupported construct fails CI instead
of being silently ignored.

Usage:
    python3 tools/schema_codegen.py            # write generated files
    python3 tools/schema_codegen.py --check    # fail if generated files are stale
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA_DIR = ROOT / "config" / "schemas"
C_OUT = ROOT / "firmware" / "components" / "contracts" / "include" / "pet" / "config_generated.h"
TS_OUT = ROOT / "integration" / "contracts" / "generated" / "pet-contracts.ts"

GENERATED_HEADER = "/* Auto-generated by tools/schema_codegen.py. Do not edit. */"

SCHEMA_KEYWORDS = {
    "$schema",
    "$id",
    "$comment",
    "title",
    "description",
    "type",
    "properties",
    "required",
    "additionalProperties",
    "enum",
    "const",
    "minimum",
    "maximum",
    "minLength",
    "maxLength",
    "pattern",
    "items",
    "prefixItems",
    "minItems",
    "maxItems",
    "default",
}
SCHEMA_TYPES = {"object", "array", "string", "integer", "number", "boolean"}


class SchemaError(ValueError):
    """Raised when a schema uses an unsupported or invalid construct."""


def load_schemas() -> dict[str, dict]:
    if not SCHEMA_DIR.is_dir():
        raise SchemaError(f"missing schema directory: {SCHEMA_DIR}")

    schemas: dict[str, dict] = {}
    for path in sorted(SCHEMA_DIR.glob("*.schema.json")):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            raise SchemaError(f"{path.name}: invalid JSON: {exc}") from exc
        check_schema(data, path.name)
        title = data.get("title")
        if not isinstance(title, str) or not title:
            raise SchemaError(f"{path.name}: missing title")
        schemas[path.name] = data
    if not schemas:
        raise SchemaError(f"no *.schema.json found in {SCHEMA_DIR}")
    return schemas


def check_schema(node: object, path: str) -> None:
    if isinstance(node, bool):
        return
    if not isinstance(node, dict):
        raise SchemaError(f"{path}: schema node must be an object")

    unknown = sorted(set(node) - SCHEMA_KEYWORDS)
    if unknown:
        raise SchemaError(f"{path}: unsupported keywords {unknown}")

    node_type = node.get("type")
    if node_type is not None and node_type not in SCHEMA_TYPES:
        raise SchemaError(f"{path}: unsupported type {node_type!r}")

    if "properties" in node:
        properties = node["properties"]
        if not isinstance(properties, dict):
            raise SchemaError(f"{path}: properties must be an object")
        for name, child in properties.items():
            check_schema(child, f"{path}.{name}")

    if "prefixItems" in node:
        if not isinstance(node["prefixItems"], list):
            raise SchemaError(f"{path}: prefixItems must be an array")
        for i, child in enumerate(node["prefixItems"]):
            check_schema(child, f"{path}[{i}]")

    if "items" in node:
        check_schema(node["items"], f"{path}[]")

    if "additionalProperties" in node:
        extra = node["additionalProperties"]
        if isinstance(extra, dict):
            check_schema(extra, f"{path}.*")
        elif not isinstance(extra, bool):
            raise SchemaError(f"{path}: additionalProperties must be boolean or schema")

    if "required" in node:
        required = node["required"]
        if not isinstance(required, list) or not all(isinstance(item, str) for item in required):
            raise SchemaError(f"{path}: required must be a string array")

    if "enum" in node and not isinstance(node["enum"], list):
        raise SchemaError(f"{path}: enum must be an array")

    for keyword in ("minLength", "maxLength", "minItems", "maxItems"):
        if keyword in node and not isinstance(node[keyword], int):
            raise SchemaError(f"{path}: {keyword} must be an integer")

    for keyword in ("minimum", "maximum"):
        if keyword in node and not isinstance(node[keyword], (int, float)):
            raise SchemaError(f"{path}: {keyword} must be a number")

    if "pattern" in node and not isinstance(node["pattern"], str):
        raise SchemaError(f"{path}: pattern must be a string")


def validate_instance(value: object, schema: dict, path: str = "<root>") -> list[str]:
    """Validate an instance against the supported JSON Schema subset."""
    errors: list[str] = []
    _validate(value, schema, path, errors)
    return errors


def _validate(value: object, schema: object, path: str, errors: list[str]) -> None:
    if schema is True or schema is None:
        return
    if schema is False:
        errors.append(f"{path}: no value allowed")
        return
    if not isinstance(schema, dict):
        errors.append(f"{path}: invalid schema node")
        return

    if "const" in schema and value != schema["const"]:
        errors.append(f"{path}: expected const {schema['const']!r}, got {value!r}")
    if "enum" in schema and value not in schema["enum"]:
        errors.append(f"{path}: expected one of {schema['enum']!r}, got {value!r}")

    node_type = schema.get("type")
    if node_type == "object":
        if not isinstance(value, dict):
            errors.append(f"{path}: expected object, got {type(value).__name__}")
            return
        properties = schema.get("properties", {})
        for name in schema.get("required", []):
            if name not in value:
                errors.append(f"{path}: missing required property '{name}'")
        extra = schema.get("additionalProperties", True)
        for name, item in value.items():
            if name in properties:
                _validate(item, properties[name], f"{path}.{name}", errors)
            elif extra is False:
                errors.append(f"{path}: unexpected property '{name}'")
            elif isinstance(extra, dict):
                _validate(item, extra, f"{path}.{name}", errors)
    elif node_type == "array":
        if not isinstance(value, list):
            errors.append(f"{path}: expected array, got {type(value).__name__}")
            return
        if len(value) < schema.get("minItems", 0):
            errors.append(f"{path}: expected at least {schema['minItems']} items")
        if "maxItems" in schema and len(value) > schema["maxItems"]:
            errors.append(f"{path}: expected at most {schema['maxItems']} items")
        for index, item in enumerate(value):
            _validate(item, schema.get("prefixItems", [])[index] if index < len(schema.get("prefixItems", [])) else schema.get("items", True), f"{path}[{index}]", errors)
    elif node_type == "string":
        if not isinstance(value, str):
            errors.append(f"{path}: expected string, got {type(value).__name__}")
            return
        if len(value) < schema.get("minLength", 0):
            errors.append(f"{path}: shorter than {schema['minLength']} characters")
        if "maxLength" in schema and len(value) > schema["maxLength"]:
            errors.append(f"{path}: longer than {schema['maxLength']} characters")
        if "pattern" in schema and re.search(schema["pattern"], value) is None:
            errors.append(f"{path}: does not match pattern {schema['pattern']!r}")
    elif node_type == "integer":
        if isinstance(value, bool) or not isinstance(value, int):
            errors.append(f"{path}: expected integer, got {type(value).__name__}")
            return
        _check_range(value, schema, path, errors)
    elif node_type == "number":
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            errors.append(f"{path}: expected number, got {type(value).__name__}")
            return
        _check_range(value, schema, path, errors)
    elif node_type == "boolean":
        if not isinstance(value, bool):
            errors.append(f"{path}: expected boolean, got {type(value).__name__}")


def _check_range(value: int | float, schema: dict, path: str, errors: list[str]) -> None:
    if "minimum" in schema and value < schema["minimum"]:
        errors.append(f"{path}: {value} is below minimum {schema['minimum']}")
    if "maximum" in schema and value > schema["maximum"]:
        errors.append(f"{path}: {value} is above maximum {schema['maximum']}")


def camel_to_snake(name: str) -> str:
    step = re.sub(r"(.)([A-Z][a-z]+)", r"\1_\2", name)
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", step).lower()


def pascal_case(name: str) -> str:
    return name[:1].upper() + name[1:]


def enum_token(value: str) -> str:
    return re.sub(r"[^0-9A-Za-z]+", "_", value).upper().strip("_")


class CGenerator:
    """Generate a C header for the device configuration schema."""

    def __init__(self, schema: dict):
        self.schema = schema
        self.macros: list[tuple[str, str]] = []
        self.enums: list[tuple[str, list[tuple[str, str]]]] = []
        self.structs: list[tuple[str, list[tuple[str, str]]]] = []

    def generate(self) -> str:
        root_type = "pet_config_t"
        fields = self._object_fields(self.schema, root_type, "PET_CFG")
        self.structs.append((root_type, fields))

        lines = [
            GENERATED_HEADER,
            "/* Source: config/schemas/device-config.schema.json */",
            "#pragma once",
            "",
            "#include <stdbool.h>",
            "#include <stdint.h>",
            "",
        ]
        lines.extend(f"#define {name} {value}" for name, value in self.macros)
        lines.append("")
        for type_name, values in self.enums:
            lines.append("typedef enum {")
            lines.extend(f"    {token} = {value}," for token, value in values)
            lines.append(f"}} {type_name};")
            lines.append("")
        for type_name, fields in self.structs:
            lines.append("typedef struct {")
            lines.extend(f"    {ctype} {name};" for ctype, name in fields)
            lines.append(f"}} {type_name};")
            lines.append("")
        return "\n".join(lines).rstrip() + "\n"

    def _object_fields(self, schema: dict, owner_type: str, prefix: str) -> list[tuple[str, str]]:
        fields: list[tuple[str, str]] = []
        properties = schema.get("properties", {})
        for raw_name, prop in properties.items():
            if not isinstance(prop, dict):
                raise SchemaError(f"device config property '{raw_name}' must be a schema")
            name = camel_to_snake(raw_name)
            field_prefix = f"{prefix}_{name.upper()}"
            prop_type = prop.get("type")

            if prop_type == "object":
                nested_type = f"{owner_type[:-2]}_{name}_t"
                nested_fields = self._object_fields(prop, nested_type, field_prefix)
                self.structs.append((nested_type, nested_fields))
                fields.append((nested_type, name))
            elif prop_type == "string":
                if "enum" in prop:
                    enum_type = f"{owner_type[:-2]}_{name}_t"
                    values = [
                        (f"{field_prefix}_{enum_token(item)}", str(index))
                        for index, item in enumerate(prop["enum"])
                    ]
                    self.enums.append((enum_type, values))
                    fields.append((enum_type, name))
                    default = prop.get("default")
                    if default is not None:
                        token = f"{field_prefix}_{enum_token(default)}"
                        self.macros.append((f"{prefix}_DEFAULT_{name.upper()}", token))
                else:
                    max_length = prop.get("maxLength")
                    if not isinstance(max_length, int):
                        raise SchemaError(f"device config string '{raw_name}' needs maxLength")
                    self.macros.append((f"{field_prefix}_MAX_LEN", str(max_length)))
                    if "default" in prop:
                        self.macros.append(
                            (f"{prefix}_DEFAULT_{name.upper()}", json.dumps(prop["default"]))
                        )
                    fields.append(("char", f"{name}[{max_length + 1}]"))
            elif prop_type == "integer":
                ctype = self._integer_type(raw_name, prop)
                if raw_name == "schemaVersion":
                    self.macros.append(("PET_CFG_SCHEMA_VERSION", str(prop.get("const"))))
                for bound, label in (("minimum", "MIN"), ("maximum", "MAX")):
                    if bound in prop:
                        self.macros.append(
                            (f"{field_prefix}_{label}", str(prop[bound]))
                        )
                if "default" in prop:
                    self.macros.append(
                        (f"{prefix}_DEFAULT_{name.upper()}", str(prop["default"]))
                    )
                fields.append((ctype, name))
            elif prop_type == "boolean":
                if "default" in prop:
                    self.macros.append(
                        (
                            f"{prefix}_DEFAULT_{name.upper()}",
                            "true" if prop["default"] else "false",
                        )
                    )
                fields.append(("bool", name))
            else:
                raise SchemaError(
                    f"device config property '{raw_name}' has unsupported type {prop_type!r}"
                )
        return fields

    @staticmethod
    def _integer_type(raw_name: str, prop: dict) -> str:
        if raw_name == "schemaVersion":
            return "uint16_t"
        minimum = prop.get("minimum", 0)
        maximum = prop.get("maximum", 2**15 - 1)
        if minimum >= 0 and maximum <= 0xFF:
            return "uint8_t"
        if minimum >= 0 and maximum <= 0xFFFF:
            return "uint16_t"
        return "int32_t"


def _ts_type(prop: dict, owner: str, raw_name: str, nested: list[str]) -> str:
    prop_type = prop.get("type")
    if prop_type == "object":
        if not prop.get("properties"):
            return "Record<string, unknown>"
        nested_name = owner + pascal_case(raw_name)
        nested.extend(_render_interface(prop, nested_name))
        return nested_name
    if prop_type == "array":
        if "prefixItems" in prop and prop.get("items") is False:
            return "[" + ", ".join(_ts_type(item, owner, raw_name + str(i), nested) for i, item in enumerate(prop["prefixItems"])) + "]"
        items = prop.get("items", True)
        if isinstance(items, dict):
            item_type = _ts_type(items, owner, raw_name + "Item", nested)
            return f"{item_type}[]"
        return "unknown[]"
    if prop_type == "string":
        if "enum" in prop:
            return " | ".join(json.dumps(value) for value in prop["enum"])
        if "const" in prop:
            return json.dumps(prop["const"])
        return "string"
    if prop_type in ("integer", "number"):
        if "const" in prop:
            return str(prop["const"])
        return "number"
    if prop_type == "boolean":
        return "boolean"
    return "unknown"


def _render_interface(schema: dict, name: str) -> list[str]:
    nested: list[str] = []
    body: list[str] = []
    required = set(schema.get("required", []))
    properties = schema.get("properties", {})

    if not properties:
        body.append("  [key: string]: unknown;")

    for raw_name, prop in properties.items():
        ts_type = _ts_type(prop, name, raw_name, nested)
        optional = "" if raw_name in required else "?"
        description = prop.get("description")
        if description:
            body.append(f"  /** {description} */")
        body.append(f"  {raw_name}{optional}: {ts_type};")

    return nested + [f"export interface {name} {{"] + body + ["}", ""]


def generate_ts(schemas: dict[str, dict]) -> str:
    lines = [GENERATED_HEADER, "/* Source: config/schemas/*.schema.json */", ""]
    for path in sorted(schemas):
        lines.extend(_render_interface(schemas[path], schemas[path]["title"]))
    return "\n".join(lines).rstrip() + "\n"


def render_all() -> dict[Path, str]:
    schemas = load_schemas()
    output = {C_OUT: CGenerator(schemas["device-config.schema.json"]).generate()}
    output[TS_OUT] = generate_ts(schemas)
    return output


def write_all() -> None:
    for path, content in render_all().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"generated {path.relative_to(ROOT)}")


def check_all() -> int:
    stale: list[Path] = []
    for path, content in render_all().items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != content:
            stale.append(path)
    if stale:
        for path in stale:
            print(f"FAIL stale generated file: {path.relative_to(ROOT)}", file=sys.stderr)
        print("run: python3 tools/schema_codegen.py", file=sys.stderr)
        return 1
    print("OK: generated contracts are up to date")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify generated files are current")
    args = parser.parse_args()
    try:
        if args.check:
            return check_all()
        write_all()
    except SchemaError as exc:
        print(f"FAIL {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
